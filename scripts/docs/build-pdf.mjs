/**
 * Renders the single-page documentation sheet to PDF using the Chromium that
 * ships with Playwright, so the PDF and the HTML can never diverge.
 */
import path from 'node:path';
import url from 'node:url';
import fs from 'node:fs';
import { chromium } from '@playwright/test';

const ROOT = path.resolve(url.fileURLToPath(new URL('../../', import.meta.url)));
const SOURCE = path.join(ROOT, 'docs/site/print.html');
const OUTPUT = path.join(ROOT, 'docs/playwright-api-framework-documentation.pdf');
const SITE_COPY = path.join(ROOT, 'docs/site/playwright-api-framework-documentation.pdf');

if (!fs.existsSync(SOURCE)) {
  console.error('docs/site/print.html is missing — run `npm run docs:html` first.');
  process.exit(1);
}

const header = `
<div style="width:100%;font-family:-apple-system,Segoe UI,sans-serif;font-size:7.5pt;color:#5a6e7d;padding:0 14mm;display:flex;justify-content:space-between;">
  <span>Playwright API Framework — Complete Documentation</span>
  <span>v1.0</span>
</div>`;

const footer = `
<div style="width:100%;font-family:-apple-system,Segoe UI,sans-serif;font-size:7.5pt;color:#5a6e7d;padding:0 14mm;display:flex;justify-content:space-between;">
  <span>Generated by npm run docs</span>
  <span><span class="pageNumber"></span> / <span class="totalPages"></span></span>
</div>`;

const browser = await chromium.launch();
const page = await browser.newPage();

await page.goto(url.pathToFileURL(SOURCE).href, { waitUntil: 'load' });
// Expand every collapsed API section so nothing is missing from the printed copy.
await page.evaluate(() => {
  document.querySelectorAll('details').forEach((element) => element.setAttribute('open', ''));
});
await page.emulateMedia({ media: 'print' });

await page.pdf({
  path: OUTPUT,
  format: 'A4',
  printBackground: true,
  displayHeaderFooter: true,
  headerTemplate: header,
  footerTemplate: footer,
  margin: { top: '16mm', bottom: '16mm', left: '14mm', right: '14mm' },
});

await browser.close();

fs.copyFileSync(OUTPUT, SITE_COPY);

const sizeMb = (fs.statSync(OUTPUT).size / 1024 / 1024).toFixed(2);
console.log(`Wrote ${path.relative(ROOT, OUTPUT)} (${sizeMb} MB)`);
